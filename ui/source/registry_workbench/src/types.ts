export type Values = Record<string, any>;
export type Schema = Record<string, any>;
export type FieldHelp = {definition?: string; units?: string; applies?: string; notes?: string; tier?: string; capture?: string};
export type Profile = {
  registry_profile: string;
  schema_version: string;
  schema: Schema;
  sections: Record<string, string>;
  help: Record<string, FieldHelp>;
};
export type CaseRow = {
  id: string;
  label: string;
  platform: string | null;
  split: string | null;
  event_date: string | null;
  status: "new" | "draft" | "approved";
  documents: number;
  missing: string[];
};
export type DocumentMeta = {id: string; kind: string; variant: string | null; exposure: string; sha256: string; characters: number};
export type Run = {
  id: string;
  document_id: string;
  provider: string;
  model: string | null;
  effort: string | null;
  status: "queued" | "running" | "succeeded" | "failed";
  proposal_status: string | null;
  warnings: string[];
  error: string | null;
  cost_usd: number | null;
  latency_s: number | null;
  has_proposal: boolean;
  contract_errors: string[];
  unresolved_mentions: {kind: string; note: string; start?: number; end?: number}[];
  unresolved: number;
  created_at: string;
  finished_at: string | null;
  response?: any;
};
export type CaseDetail = {
  id: string;
  label: string;
  platform: string | null;
  split: string | null;
  source: string;
  event_date: string | null;
  version: number;
  status: string;
  draft_revision_id: string | null;
  approved_revision_id: string | null;
  draft: Values | null;
  approved: Values | null;
  documents: DocumentMeta[];
  runs: Run[];
  revisions: {id: string; number: number; mode: string; created_at: string; approved_at: string | null}[];
};
export type SourceDocument = DocumentMeta & {case_id: string; text: string};
export type Span = {document_id: string; start: number; end: number};
export type Status = {claude_configured: boolean; prompt_digest: string; egress: string};
